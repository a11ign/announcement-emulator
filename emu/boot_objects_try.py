"""Boot NVDA release-2026.1.1's own Python on Linux for stage 2: the stage-1 stub list MINUS the modules the stand-in now
supplies for real (NVDAHelper.localLib, oleacc constants, IA2 constants), so IAccessibleHandler's role/state tables are NVDA's."""
import sys, os, types, ast, json, tempfile, builtins, pathlib
R = pathlib.Path.home() / 'spikes/announcement-emulator-5661'
SRC = str(R / 'nvda-src/source')
sys.path[:0] = [str(R / 'q2'), str(R / 'emu'), SRC]
os.chdir(SRC)
import stubs, standin
builtins._ = lambda s: s; builtins.ngettext = lambda a, b, n: a if n == 1 else b
builtins.pgettext = lambda c, s: s; builtins.npgettext = lambda c, a, b, n: a if n == 1 else b
STUB = ('winBindings,winUser,winKernel,easeOfAccess,louisHelper,objidl,oleTypes,JABHandler,braille,gui,tones,nvwave,ui,vision,bdDetect,'
        'brailleInput,brailleViewer,wasapi,mouseHandler,eventHandler,api,review,NVDAObjects.window,NVDAObjects.behaviors,NVDAObjects.IAccessible,NVDAObjects.UIA,NVDAObjects.JAB,NVDAObjects.IAccessible.mozilla,appModuleHandler,winreg,winsound,comtypes,wx,UIAHandler,core,watchdog').split(',')
stubs.install(STUB)
LOCALLIB = standin.LocalLib()
nh = types.ModuleType('NVDAHelper'); nh.localLib = LOCALLIB; sys.modules['NVDAHelper'] = nh
# oleacc: the real constant lines of NVDA's own oleacc.py (the rest of that file needs comtypes' typelib loader)
ole = types.ModuleType('oleacc')
for node in ast.parse(open(SRC + '/oleacc.py').read()).body:
    if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, (int, str)):
        for t in node.targets:
            if isinstance(t, ast.Name): setattr(ole, t.id, node.value.value)
sys.modules['oleacc'] = ole
# comInterfaces: generated by scons from typelibs, absent from the source tree; supply the IA2 constants it would hold
ci = stubs.StubModule('comInterfaces'); sys.modules['comInterfaces'] = ci
ia2 = stubs.StubModule('comInterfaces.IAccessible2Lib')
for k, v in {**json.loads((R / 'emu/tables.json').read_text())['ia2_role'], **json.loads((R / 'emu/tables.json').read_text())['ia2_state']}.items(): setattr(ia2, k, v)
sys.modules['comInterfaces.IAccessible2Lib'] = ia2; ci.IAccessible2Lib = ia2
import globalVars
globalVars.appDir = str(R / 'nvda-appdir'); globalVars.appArgs.configPath = tempfile.mkdtemp(prefix='nvda-cfg-'); globalVars.appArgs.disableAddons = True
# The system tests' own NVDA settings (tests/system/nvdaSettingsFiles/standard-dontShowWelcomeDialog.ini, chromeTests.robot:32), unmodified:
# they turn reportLinkType and unicodeNormalization OFF, which changes the expected speech.
import shutil; shutil.copy(R / 'nvda-src/tests/system/nvdaSettingsFiles/standard-dontShowWelcomeDialog.ini', globalVars.appArgs.configPath + '/nvda.ini')
import config; config.initialize()
import languageHandler; languageHandler.setLanguage('en')
